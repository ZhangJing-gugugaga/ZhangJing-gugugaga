"""card-termify.svg — 1300x360. Termify showcase: terminal window with the
REAL ASCII art generated by Termify itself (tools/src/termify_star.txt),
lines reveal staggered, cursor blinks. 3-step chips (true sequence).
"""
import sys, pathlib
sys.path.insert(0, str(pathlib.Path(__file__).parent))
from palette import PINK, TEXT, DIM, FAINT, PANEL, PANEL2, GREEN
from svgkit import SVG, pixel_frame
import pixelfont as pf

W, H = 1300, 360
s = SVG(W, H, "Termify 项目卡：万物皆可终端，ASCII 艺术由 Termify 生成")
pixel_frame(s, PINK)
s.use_blink(); s.use_rise()

def txt(x, y, t, cell, color, shadow=None, cls=None):
    els, w, h = pf.text(x, y, t, cell, color, shadow)
    s.add(f'<g class="{cls}">{els}</g>' if cls else els)
    return w, h

# left column
txt(60, 46, "TERMIFY", 6, PINK, shadow="#260A18")
txt(60, 112, "万物皆可终端。", 2, TEXT)
txt(60, 140, "这张卡里的 ASCII 艺术，由 Termify 生成。", 2, TEXT)
txt(60, 172, "GIF / IMAGE / VIDEO -> TERMINAL", 2, DIM)

# 3-step chips (true sequence -> numbered)
steps = ["1 UPLOAD", "2 PICK STYLE", "3 EXPORT"]
cx = 60
for i, c in enumerate(steps):
    cw, _ = pf.measure(c, 2)
    pad = 14
    s.style(f".p{i}{{animation:rs .6s cubic-bezier(.2,.7,.3,1) {0.35+0.12*i:.2f}s both}}")
    s.add(
        f'<g class="p{i}"><rect x="{cx}" y="222" width="{cw+2*pad}" height="40" '
        f'fill="{PANEL2}" stroke="{FAINT}" stroke-width="2"/>'
    )
    els, _, _ = pf.text(cx + pad, 232, c, 2, PINK if i == 0 else TEXT)
    s.add(els + "</g>")
    cx += cw + 2 * pad + 16

txt(60, 300, "LIVE DEMO: TERMIFY.MOONZJ.COM", 2, DIM)

# right: terminal window
tx, ty, tw_, th = 700, 40, 540, 288
s.style(".term{animation:rs .8s cubic-bezier(.2,.7,.3,1) .1s both}")
term = [
    f'<g class="term"><rect x="{tx}" y="{ty}" width="{tw_}" height="{th}" fill="{PANEL}" '
    f'stroke="{FAINT}" stroke-width="3"/>',
    f'<rect x="{tx}" y="{ty}" width="{tw_}" height="30" fill="{PANEL2}"/>',
]
for i in range(3):
    term.append(f'<rect x="{tx+16+i*20}" y="{ty+12}" width="10" height="10" fill="{FAINT}"/>')
term.append(f'<rect x="{tx+80}" y="{ty+13}" width="120" height="6" fill="#3E4C5E"/>')  # title bar text
# prompt line
els, _, _ = pf.text(tx + 20, ty + 44, "$ termify star.png --charset ascii", 2, GREEN)
term.append(els)
s.add("".join(term))

# ASCII art from Termify itself — char-cell mono grid, density-mapped colors
art = pathlib.Path(__file__).parent / "src" / "termify_star.txt"
lines = art.read_text(encoding="utf-8").splitlines()
art_x, art_y = tx + 20, ty + 70
cw, chh = 6, 9

def art_rows(lines):
    """Row-major runs of the mono ASCII art, four density tones."""
    TONE = {"@": "t3", "#": "t2", "%": "t1"}
    for row in lines:
        runs = []
        rx = None; cur = None
        for gx, c in enumerate(list(row) + [" "]):
            k = TONE.get(c)
            if k != cur:
                if rx is not None and gx > rx:
                    runs.append((rx, gx, cur))
                rx = gx if k else None
                cur = k
        yield runs

parts = []
TONE_COLOR = {"t3": PINK, "t2": "#D06CA6", "t1": "#9B5F80", "t0": "#6E4459"}
for li, runs in enumerate(art_rows(lines)):
    delay = 0.15 + li * 0.06
    s.style(f".a{li}{{animation:rs .4s cubic-bezier(.2,.7,.3,1) {delay:.2f}s both}}")
    seg = ""
    for rx0, rx1, kind in runs:
        seg += (f'<rect x="{art_x + rx0*cw}" y="{art_y + li*chh}" '
                f'width="{(rx1-rx0)*cw}" height="{chh-2}" fill="{TONE_COLOR[kind]}"/>')
    parts.append(f'<g class="a{li}">{seg}</g>')
s.add("".join(parts))
# blinking cursor at end
last_y = art_y + len(lines) * chh + 4
s.add(f'<rect class="bl" x="{art_x}" y="{last_y}" width="10" height="12" fill="{GREEN}"/>')
s.add("</g>")

n = s.save(pathlib.Path(__file__).parent.parent / "assets" / "card-termify.svg")
print("card-termify.svg", n, "bytes")
